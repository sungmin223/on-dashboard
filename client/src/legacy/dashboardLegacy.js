const CH_DRILL = {};
function chData(ch){
  if (CH_DRILL[ch]) return CH_DRILL[ch];
  const list = (CH_CUST[ch] || []).map(r => ({
    name: r[0], rate: r[1], m: [r[2],r[3],r[4],r[5],r[6]],   // 1~5월
    cum: r[2]+r[3]+r[4]+r[5]+r[6],
  }));
  const total = list.reduce((s,r) => s + r.cum, 0);
  list.forEach((r,i) => { r.rank = i+1; r.share = total ? r.cum/total*100 : 0; });
  return (CH_DRILL[ch] = { list, total });
}
function chDrillRows(ch, q){
  const { list } = chData(ch);
  q = (q || "").trim().toLowerCase();
  const f = q ? list.filter(r => r.name.toLowerCase().includes(q)) : list;
  if (!f.length) return `<tr><td colspan="10" style="text-align:center;color:var(--text-3);padding:18px;">검색 결과 없음 ‘${q}’</td></tr>`;
  return f.map(r => `<tr>
      <td style="color:var(--text-3);">${r.rank}</td>
      <td style="color:var(--text);font-weight:600;white-space:nowrap;">${r.name}</td>
      ${r.m.map(v => `<td style="text-align:right;color:var(--text-3);">${won(v)}</td>`).join("")}
      <td style="text-align:right;color:var(--text);font-weight:700;">${won(r.cum)}</td>
      <td style="text-align:right;color:var(--text-2);">${r.share.toFixed(1)}%</td>
      <td style="text-align:right;color:var(--text-3);">${r.rate==null ? "—" : r.rate.toFixed(1)+"%"}</td>
    </tr>`).join("");
}
