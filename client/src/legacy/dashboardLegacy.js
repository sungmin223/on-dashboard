function StatusBadge(type, text) {
  return `<span class="badge badge-${type}"><span class="dot"></span>${text}</span>`;
}

function EmptyState({ size = "md", icon = "🔌", msg = EMPTY.needData, sub = "" } = {}) {
  return `
    <div class="empty ${size}">
      <div class="e-icon">${icon}</div>
      <div class="e-msg">${msg}</div>
      ${sub ? `<div class="e-sub">${sub}</div>` : ""}
    </div>`;
}

/* KPI 카드 — value 미지정 시 '—'(미연결), 지정 시 실데이터 표시 */
function KpiCard({ label, icon = "📊", value = "", unit = "", foot, tone = "warn", src = "" }) {
  const val = value
    ? `${value}${unit ? `<span style="font-size:14px;font-weight:600;color:var(--text-3);"> ${unit}</span>` : ""}`
    : "—";
  return `
    <div class="card kpi">
      <div class="kpi-top">
        <span class="kpi-label">${label}</span>
        <span class="kpi-icon">${icon}</span>
      </div>
      <div class="kpi-value"${value ? ' style="color:var(--text);"' : ""}>${val}</div>
      <div class="kpi-foot">${StatusBadge(tone, foot)}${src ? `<span class="kpi-src">${src}</span>` : ""}</div>
    </div>`;
}

function Section({ num, title, sheet = "", hint = "", right = "", body }) {
  return `
    <section class="section">
      <div class="section-head">
        <div class="title">
          <span class="num">${num}</span>
          <h2>${title}</h2>
          ${sheet ? `<span class="sheet">${sheet}</span>` : ""}
          ${hint ? `<span class="hint">${hint}</span>` : ""}
        </div>
        <div>${right}</div>
      </div>
      ${body}
    </section>`;
}

/* 표 골격 — 컬럼명은 data_schema.md와 100% 일치. 본문은 빈 상태 1행만(가짜 행 금지) */
function DataTable(columns, { emptyMsg = EMPTY.needData, tone = "warn" } = {}) {
  const ths = columns.map(c =>
    `<th>${c.k}${c.req ? `<span class="req">●</span>` : ""}${c.auto ? `<span class="auto">자동</span>` : ""}</th>`
  ).join("");
  return `
    <div class="table-wrap">
      <table class="tbl">
        <thead><tr>${ths}</tr></thead>
        <tbody>
          <tr class="tbl-empty-row"><td colspan="${columns.length}">${StatusBadge(tone, emptyMsg)}</td></tr>
        </tbody>
      </table>
    </div>`;
}

function Tabs(items, activeIdx = 0) {
  return `<div class="tabs">${items.map((t,i)=>`<button class="tab ${i===activeIdx?"active":""}" data-tab="${i}">${t}</button>`).join("")}</div>`;
}

